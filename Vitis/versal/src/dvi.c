/*
 * Then the registers the Linux idt8t49n24x driver writes when it sets Q2 to 148.5 MHz
 * (assigned-clock-rates): VCO 3267 MHz = 2 x 40 MHz x (DSM 40 + 0x1ACCCC / 2^21), Q2 integer
 * divider 11 (148.5 MHz = 3267 / 22), only Q2 enabled. Values read back from the VCK190 running
 * the validated Linux image.
 */
static const u8 clkgen_q2_148m5[][2] = {
	{0x25, 0x00}, {0x26, 0x28},                     /* DSM_INT = 40 */
	{0x28, 0x1A}, {0x29, 0xCC}, {0x2A, 0xCC},       /* DSMFRAC = 0x1ACCCC */
	{0x3F, 0x00}, {0x40, 0x00}, {0x41, 0x00},       /* Q0 dividers (unused) */
	{0x42, 0x00}, {0x43, 0x00}, {0x44, 0x00},       /* Q1 integer divider (unused) */
	{0x45, 0x00}, {0x46, 0x00}, {0x47, 0x0B},       /* Q2 integer divider = 11 */
	{0x48, 0x00}, {0x49, 0x00}, {0x4A, 0x00},       /* Q3 integer divider (unused) */
	{0x57, 0x00}, {0x58, 0x00}, {0x59, 0x00}, {0x5A, 0x00},   /* Q1 fractional */
	{0x5B, 0x00}, {0x5C, 0x00}, {0x5D, 0x00}, {0x5E, 0x00},   /* Q2 fractional = 0 */
	{0x5F, 0x00}, {0x60, 0x00}, {0x61, 0x00}, {0x62, 0x00},   /* Q3 fractional */
	{0x39, 0x04},                                   /* OUTEN: Q2 */
	{0x3E, 0x44}, {0x3D, 0x44},                     /* output modes */
	{0x6F, 0x0B},                                   /* Q_DIS: Q0, Q1, Q3 disabled */
};

/* The 8T49N241 can NACK while it applies a previous block (the Linux driver retries 5 times) */
static int clkgen_write(u16 reg, const u8 *data, unsigned len)
{
	u8 buf[2 + 16];
	if (len > 16)
		return XST_FAILURE;
	buf[0] = reg >> 8;
	buf[1] = reg & 0xFF;
	for (unsigned i = 0; i < len; i++)
		buf[2 + i] = data[i];
	for (int retry = 0; retry < 5; retry++) {
		if (IicWrite(IicIdx, CLKGEN_ADDR, buf, 2 + len) == XST_SUCCESS)
			return XST_SUCCESS;
		usleep(10000);
	}
	return XST_FAILURE;
}

static int clkgen_read(u16 reg, u8 *val)
{
	u8 a[2] = { reg >> 8, reg & 0xFF };
	if (IicWrite(IicIdx, CLKGEN_ADDR, a, 2) != XST_SUCCESS)
		return XST_FAILURE;
	return IicRead(IicIdx, CLKGEN_ADDR, val, 1);
}

static int clkgen_init(void)
{
	unsigned n = sizeof(clkgen_settings);
	for (unsigned off = 0; off < n; off += 16) {
		unsigned len = (n - off) < 16 ? (n - off) : 16;
		if (clkgen_write(off, &clkgen_settings[off], len) != XST_SUCCESS) {
			xil_printf("DVI: 8T49N241 write at 0x%03x failed\r\n", off);
			return XST_FAILURE;
		}
	}
	for (unsigned i = 0; i < sizeof(clkgen_q2_148m5) / sizeof(clkgen_q2_148m5[0]); i++) {
		if (clkgen_write(clkgen_q2_148m5[i][0], &clkgen_q2_148m5[i][1], 1) != XST_SUCCESS) {
			xil_printf("DVI: 8T49N241 write 0x%02x failed\r\n", clkgen_q2_148m5[i][0]);
			return XST_FAILURE;
		}
	}
	/* verify the Q2 divider and output enable */
	u8 q2 = 0, oe = 0;
	clkgen_read(0x47, &q2);
	clkgen_read(0x39, &oe);
	xil_printf("DVI: 8T49N241 programmed (Q2 148.5 MHz: N 0x%02x, OUTEN 0x%02x)\r\n", q2, oe);
	return (q2 == 0x0B && oe == 0x04) ? XST_SUCCESS : XST_FAILURE;
}

static int rt_w(u8 reg, u8 val)
{
	u8 b[2] = { reg, val };
	return IicWrite(IicIdx, RETIMER_ADDR, b, 2);
}

static int rt_r(u8 reg, u8 *val)
{
	if (IicWrite(IicIdx, RETIMER_ADDR, &reg, 1) != XST_SUCCESS)
		return XST_FAILURE;
	return IicRead(IicIdx, RETIMER_ADDR, val, 1);
}

static int write_list(const u8 (*list)[2], unsigned n)
{
	for (unsigned i = 0; i < n; i++)
		if (rt_w(list[i][0], list[i][1]) != XST_SUCCESS)
			return XST_FAILURE;
	return XST_SUCCESS;
}

/* Same register values as Yocto/bsp/dvi-out dvi-init.sh (TMDS 1.485 Gb/s, DVI 1080p60) */
static const u8 dp159_cfg[][2] = {
	{0x09, 0x06},   /* misc control */
	{0x0B, 0x80},   /* SLEW_CTL = 10, TX_TERM_CTL = 00 (HDMI 1.4 rates) */
	{0x0C, 0x48},   /* VSWING_DATA/CLK +14%, no pre-emphasis */
	{0x0D, 0x00},
	{0x0A, 0x35},   /* automatic redriver/retimer, DDC training off */
};
static const u8 tmds1204_cfg[][2] = {
	/* init (lane swap for the VEK280 layout) */
	{0x0A, 0x8E}, {0x0B, 0x43}, {0x0C, 0x70}, {0x0D, 0x22}, {0x0E, 0x97}, {0x11, 0x0F},
	{0x09, 0x02},
	/* TMDS <= 1.65 Gb/s */
	{0x11, 0x00}, {0x0D, 0x22}, {0x12, 0x03}, {0x13, 0x00}, {0x14, 0x03}, {0x15, 0x05},
	{0x16, 0x03}, {0x17, 0x05}, {0x18, 0x03}, {0x19, 0x05}, {0x20, 0x00}, {0x31, 0x00},
	{0x11, 0x0F},
};

static int retimer_init(void)
{
	u8 id0 = 0, id1 = 0, dev = 0;
	if (rt_r(0x00, &id0) == XST_SUCCESS && rt_r(0x01, &id1) == XST_SUCCESS &&
	    id0 == 0x44 && id1 == 0x50) {
		xil_printf("DVI: SN65DP159 retimer found, configuring for TMDS 1.485 Gb/s\r\n");
		return write_list(dp159_cfg, sizeof(dp159_cfg) / sizeof(dp159_cfg[0]));
	}
	if (rt_r(0x08, &dev) == XST_SUCCESS && dev != 0x00) {
		xil_printf("DVI: TMDS1204 redriver found (reg 0x08 = 0x%02x), configuring for TMDS 1.485 Gb/s\r\n", dev);
		return write_list(tmds1204_cfg, sizeof(tmds1204_cfg) / sizeof(tmds1204_cfg[0]));
	}
	xil_printf("DVI: no retimer/redriver answers at 0x5E\r\n");
	return XST_FAILURE;
}

static void ctrl_write(u32 v)
{
	Ctrl = v;
	XGpio_DiscreteWrite(&DviGpio, 2, Ctrl);
}

u32 dvi_status(void)
{
	return XGpio_DiscreteRead(&DviGpio, 1);
}

void dvi_print_status(void)
{
	u32 st = dvi_status();
	xil_printf("DVI: status 0x%08x: link %d, streaming %d, underflow %d, overflow %d, HPD %d, "
		   "GT retries %d, FIFO watchdog %d\r\n", st,
		   (st & ST_LINK_READY) != 0, (st & ST_STREAMING) != 0, (st & ST_UNDERFLOW) != 0,
		   (st & ST_OVERFLOW) != 0, (st & ST_HPD) != 0, (st >> 8) & 0xFF, (st >> 16) & 0xF);
}

void dvi_pattern(int on)
{
	ctrl_write(on ? (Ctrl | CTRL_PATTERN) : (Ctrl & ~CTRL_PATTERN));
}

int dvi_init(void)
{
	int status = XST_SUCCESS;

	if (XGpio_Initialize(&DviGpio, XPAR_VIDEO_OUTPUT_AXI_GPIO_DVI_BASEADDR) != XST_SUCCESS) {
		xil_printf("DVI: status/control GPIO init failed\r\n");
		return XST_FAILURE;
	}
	XGpio_SetDataDirection(&DviGpio, 1, 0xFFFFFFFF);
	XGpio_SetDataDirection(&DviGpio, 2, 0x00000000);
	ctrl_write(CTRL_TX_EN);
	if ((dvi_status() >> 20) != 0xD72)
		xil_printf("DVI: unexpected status id 0x%08x\r\n", dvi_status());

	if (IicAxiInit(NULL, XPAR_VIDEO_OUTPUT_AXI_IIC_HDMI_BASEADDR, &IicIdx) != XST_SUCCESS)
		return XST_FAILURE;
	if (clkgen_init() != XST_SUCCESS)
		status = XST_FAILURE;
	usleep(20000);
	if (retimer_init() != XST_SUCCESS) {
		xil_printf("DVI: retimer/redriver configuration FAILED\r\n");
		status = XST_FAILURE;
	}

	/* Restart the transceivers + CDC FIFO now that the reference clock is final, wait for the
	 * link, then clear the sticky flags (history of the clock change) and judge a fresh window. */
	ctrl_write(Ctrl | CTRL_GT_RESET);
	usleep(100000);
	ctrl_write(Ctrl & ~CTRL_GT_RESET);
	int up = 0;
	for (int i = 0; i < 50 && !up; i++) {
		up = (dvi_status() & ST_LINK_READY) != 0;
		if (!up)
			usleep(100000);
	}
	ctrl_write(Ctrl | CTRL_CLEAR);
	usleep(10000);
	ctrl_write(Ctrl & ~CTRL_CLEAR);
	usleep(500000);
	u32 st = dvi_status();
	if (!up || !(st & ST_STREAMING) || (st & (ST_UNDERFLOW | ST_OVERFLOW))) {
		xil_printf("DVI: link NOT up / FIFO not streaming cleanly\r\n");
		status = XST_FAILURE;
	} else {
		xil_printf("DVI: link up, 1080p60\r\n");
	}
	dvi_print_status();
	return status;
}
